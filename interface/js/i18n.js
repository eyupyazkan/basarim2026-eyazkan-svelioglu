const FAMILY = {
  en: { SS: 'Single TM', OPDT: 'Out-of-plane ordered double TM', IPDT: 'In-plane ordered double TM',
        IPV: 'In-plane ordered vacancy', SSM: 'Solid solution, M site', SSX: 'Solid solution, X site' },
  tr: { SS: 'Tek geçiş metali', OPDT: 'Düzlem dışı düzenli çift GM', IPDT: 'Düzlem içi düzenli çift GM',
        IPV: 'Düzlem içi düzenli boşluk', SSM: 'Katı çözelti, M bölgesi', SSX: 'Katı çözelti, X bölgesi' },
};

let LANG = 'en';
export function setLang(l) { LANG = (l === 'tr') ? 'tr' : 'en'; document.documentElement.lang = LANG; }
export function lang() { return LANG; }
export function t(key, vars) {
  let s = (S[LANG] && S[LANG][key]);
  if (s === undefined) s = S.en[key];
  if (s === undefined) return key;
  if (Array.isArray(s)) return s;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m));
  return s;
}
export function family(code) { return (FAMILY[LANG] && FAMILY[LANG][code]) || FAMILY.en[code] || code || '—'; }
export function locale() { return LANG === 'tr' ? 'tr-TR' : 'en-US'; }
export function applyStatic(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
}
